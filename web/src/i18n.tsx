export function applyChrome(theme?: Theme, size?: TextSize) {
  try {
    const t = theme || ((localStorage.getItem(THEME_KEY) as Theme) || "dark");
    const s = size || ((localStorage.getItem(SIZE_KEY) as TextSize) || "normal");
    document.documentElement.dataset.theme = t === "light" ? "light" : "dark";
    document.documentElement.dataset.textSize = s === "large" ? "large" : "normal";
  } catch {
    /* ignore */
  }
}

