const dict: Record<Locale, Record<string, string>> = { en: { ...en }, tr };

function detect(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE);
    if (saved === "en" || saved === "tr") return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("tr")) return "tr";
  return "en";
}

function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  let s = template;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  theme: Theme;
  setTheme: (t: Theme) => void;
  textSize: TextSize;
  setTextSize: (s: TextSize) => void;
  t: (key: keyof typeof en, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detect);
  const [theme, setThemeState] = useState<Theme>(() => {
    try {
      return localStorage.getItem(THEME_KEY) === "light" ? "light" : "dark";
    } catch {
      return "dark";
    }
  });
  const [textSize, setSizeState] = useState<TextSize>(() => {
    try {
      return localStorage.getItem(SIZE_KEY) === "large" ? "large" : "normal";
    } catch {
      return "normal";
    }
  });

  const value = useMemo<Ctx>(() => {
    const setLocale = (l: Locale) => {
      setLocaleState(l);
      try {
        localStorage.setItem(STORAGE, l);
      } catch {
        /* ignore */
      }
      document.documentElement.lang = l === "tr" ? "tr" : "en";
    };
    const setTheme = (next: Theme) => {
      setThemeState(next);
      try {
        localStorage.setItem(THEME_KEY, next);
      } catch {
        /* ignore */
      }
      applyChrome(next, textSize);
    };
    const setTextSize = (next: TextSize) => {
      setSizeState(next);
      try {
        localStorage.setItem(SIZE_KEY, next);
      } catch {
        /* ignore */
      }
      applyChrome(theme, next);
    };
    document.documentElement.lang = locale === "tr" ? "tr" : "en";
    applyChrome(theme, textSize);
    return {
      locale,
      setLocale,
      theme,
      setTheme,
      textSize,
      setTextSize,
      t: (key, vars) => fill(dict[locale][key] || dict.en[key] || key, vars),
    };
  }, [locale, theme, textSize]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}

export function LanguageToggle() {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className="mode-toggle lang-toggle" role="group" aria-label={t("langLabel")}>
      <button type="button" className={locale === "en" ? "active" : ""} onClick={() => setLocale("en")}>
        {t("langEn")}
      </button>
      <button type="button" className={locale === "tr" ? "active" : ""} onClick={() => setLocale("tr")}>
        {t("langTr")}
      </button>
    </div>
  );
}
